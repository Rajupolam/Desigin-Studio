export const CURRENCY_RATES: Record<CurrencyCode, { symbol: string; rate: number }> = {
  USD: { symbol: '$', rate: 1 },
  EUR: { symbol: '€', rate: 0.92 },
  GBP: { symbol: '£', rate: 0.79 },
  JPY: { symbol: '¥', rate: 154 },
};

export const formatPrice = (usdAmount: number, currency: CurrencyCode): string => {
  const info = CURRENCY_RATES[currency] || CURRENCY_RATES.USD;
  const converted = Math.round(usdAmount * info.rate);
  return `${info.symbol}${converted.toLocaleString()}`;
};

